function defineAbility(definition: AbilityDefinition): AbilityDefinition {
  return Object.freeze({
    ...definition,
    hitShape: Object.freeze({ ...definition.hitShape }),
    damage: definition.damage ? Object.freeze({ ...definition.damage }) : undefined,
    movement: definition.movement ? Object.freeze({ ...definition.movement }) : undefined,
    statuses: definition.statuses
      ? Object.freeze(definition.statuses.map((status) => Object.freeze({ ...status })))
      : undefined,
  })
}

function defineKit(
  definition: Omit<HeroKit, 'abilities'> & {
    readonly abilities: Readonly<Record<AbilitySlot, AbilityDefinition>>
  },
): HeroKit {
  const abilities = Object.fromEntries(
    ABILITY_SLOTS.map((slot) => [slot, defineAbility(definition.abilities[slot])]),
  ) as unknown as Readonly<Record<AbilitySlot, AbilityDefinition>>

  return Object.freeze({
    ...definition,
    stats: Object.freeze({ ...definition.stats }),
    abilities: Object.freeze(abilities),
  })
}

