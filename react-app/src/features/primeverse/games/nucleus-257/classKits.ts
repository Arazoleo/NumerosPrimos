export const HERO_KIT_LIST: readonly HeroKit[] = Object.freeze(
  HERO_IDS.map((id) => HERO_KITS[id]),
)

export function isHeroId(value: string): value is HeroId {
  return HERO_IDS.includes(value as HeroId)
}

export function getHeroKit(id: HeroId | string): HeroKit {
  if (!isHeroId(id)) throw new RangeError(`Unknown Núcleo 257 hero: ${id}`)
  return HERO_KITS[id]
}
